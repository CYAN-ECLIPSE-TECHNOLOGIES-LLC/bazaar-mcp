"""make_verdict_snapshot — build the stamped verdict snapshot (gate A1).

The pre-packaging server read Test Bench scorecards live from
../test-bench/results/ — a sibling path that does not exist inside a
wheel. This generator reads every scorecard referenced by catalog.json,
summarises it with the *same* code the server runs
(eclipse_bazaar.catalog.summarize_card), pins the card file's sha256,
and writes src/eclipse_bazaar/data/verdict_snapshot.json. A packaged run
therefore returns byte-identical summaries to a repo run on the same
catalog build; the snapshot is regenerated by tools/sync_package_data.py
and the parity test fails if a card changed without regeneration.
"""
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from eclipse_bazaar.catalog import summarize_card  # noqa: E402


def main():
    cat = json.loads((ROOT / "catalog.json").read_text())
    cetech = ROOT.parent
    cards = {}
    missing = []
    for p in cat["products"]:
        ref = (p.get("certification") or {}).get("scorecard_ref")
        if not ref:
            continue
        path = cetech / ref
        if not path.exists():
            missing.append(ref)
            continue
        raw = path.read_bytes()
        cards[ref] = {"sha256": hashlib.sha256(raw).hexdigest(),
                      "summary": summarize_card(json.loads(raw))}
    snapshot = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "generator": "tools/make_verdict_snapshot.py",
        "source": "test-bench/results (referenced by catalog.json scorecard_ref)",
        "catalog_built": cat.get("built"),
        "cards": cards,
    }
    out = ROOT / "src/eclipse_bazaar/data/verdict_snapshot.json"
    out.write_text(json.dumps(snapshot, indent=1, sort_keys=True) + "\n")
    print(f"snapshot: {len(cards)} cards -> {out}")
    if missing:
        print(f"WARNING: {len(missing)} referenced cards missing on disk: {missing}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
