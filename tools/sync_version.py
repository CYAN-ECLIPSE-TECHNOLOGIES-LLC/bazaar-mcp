"""sync_version — server.json is the single source of truth for the version.

Gate A3 (two-system version law): the Registry version and the PyPI
version must never drift. server.json carries the canonical version;
this script stamps it into:
  * VERSION                          (repo root; pyproject dynamic version)
  * src/eclipse_bazaar/_version.py   (runtime __version__)

Run via tools/sync_package_data.py before every build. The drift test
(tests/test_version_drift.py) fails if the three ever disagree.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def version_from_server_json() -> str:
    return json.loads((ROOT / "server.json").read_text())["version"]


def main():
    v = version_from_server_json()
    (ROOT / "VERSION").write_text(v + "\n")
    (ROOT / "src/eclipse_bazaar/_version.py").write_text(
        "# GENERATED by tools/sync_version.py from server.json — do not edit.\n"
        f'__version__ = "{v}"\n')
    print(f"synced version {v} -> VERSION, src/eclipse_bazaar/_version.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
